export interface AiTool {
  slug: string;
  name: string;
  developer: string;
  /** یک‌خطی معرفی — همین متن در کارت دایره نمایش داده می‌شود */
  tagline: string;
  website: string;
  category: ToolCategoryId;
  /** کارکرد اصلی — پاسخ مستقیم به «این ابزار دقیقاً چه می‌کند؟» */
  whatItDoes: string;
  /** مناسب برای چه کسانی/چه کارهایی */
  bestFor: string[];
  /** خلاصهٔ قیمت برای کارت دایره (واحد: دلار رسمی) */
  priceLabel: string;
  /** دقیقاً چه چیزی رایگان می‌شود — مهم‌ترین فیلد برای کاربر ایرانی */
  freeTier: string;
  /** پلن‌های پولی با قیمت رسمی دلار */
  paidPlans: { name: string; price: string }[];
  /** برای اسکیمای SoftwareApplication — بازهٔ قیمت دلاری؛ اگر رایگان نیست null */
  priceUsd: [number, number] | null;
  /** راه پرداخت از ایران — تومانی یا کارت خارجی یا واسطه */
  paymentInIran: string;
  access: AccessLevel;
  /** توضیح صادقانهٔ وضعیت دسترسی، بدون ادعای قطعی که فردا غلط شود */
  accessNote: string;
  /** نکتهٔ ایران — تجربهٔ کاربردی که مرجع انگلیسی هیچ‌وقت نمی‌نویسد */
  iranTip: string;
  /** جایگزین رایگان یا تومانی */
  alternative: string;
  /** حکم تک‌راه — یک پاراگراف قضاوت صریح */
  verdict: string;
  /** امتیاز ۰ تا ۱۰ از نگاه کاربر ایرانی (کیفیت + دسترسی + هزینه) */
  score: number;
  /** مقالهٔ مرتبط سایت (slug) برای لینک‌سازی داخلی */
  relatedArticle?: string;
  /** تاریخ آخرین بررسی قیمت/دسترسی — بدون تاریخ، عدد ممنوع */
  lastChecked: string;
}

