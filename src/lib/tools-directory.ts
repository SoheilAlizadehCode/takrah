export const getTool = (slug: string): AiTool | undefined =>
  aiTools.find((t) => t.slug === slug);

export const getToolCategory = (id: ToolCategoryId): ToolCategory =>
  toolCategories.find((c) => c.id === id) ?? toolCategories[0];

export const getToolsByCategory = (id: ToolCategoryId): AiTool[] =>
  aiTools.filter((t) => t.category === id);

/** ابزارهای هم‌دسته — برای لینک‌سازی داخلی در صفحهٔ پروفایل */
export const getRelatedTools = (tool: AiTool, limit = 3): AiTool[] =>
  aiTools.filter((t) => t.category === tool.category && t.slug !== tool.slug).slice(0, limit);

/** فرمت امتیاز با رقم فارسی — ۹.۵ */
export const formatScore = (score: number): string =>
  score.toLocaleString("fa-IR", { maximumFractionDigits: 1 });
